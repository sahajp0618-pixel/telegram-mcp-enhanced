"""The shared request scheduler.

Added by Telegram MCP Enhanced.

Every Telegram operation started through MCP acquires a slot here, so no
individual tool — and no number of concurrent MCP requests — can outrun the
configured limits. The scheduler combines four things:

* a concurrency guard, so parallel MCP calls cannot bypass the limiter;
* per-class token buckets;
* a configurable minimum interval between dispatches;
* a global cooldown, set when Telegram reports a flood wait, which holds back
  every queued operation instead of letting each one discover the wait itself.
"""

from __future__ import annotations

import asyncio
import logging
import time

from collections.abc import AsyncGenerator, Awaitable, Callable
from contextlib import asynccontextmanager

from mcp_telegram.config import RateLimitSettings
from mcp_telegram.errors import RateLimitedError
from mcp_telegram.reliability.rate_limiter import MultiClassRateLimiter
from mcp_telegram.types import SchedulerStats

__all__ = ["RequestScheduler"]

logger = logging.getLogger(__name__)

Clock = Callable[[], float]
Sleeper = Callable[[float], Awaitable[None]]


class RequestScheduler:
    """Serialises and paces Telegram traffic generated by MCP clients."""

    def __init__(
        self,
        settings: RateLimitSettings,
        limiter: MultiClassRateLimiter,
        *,
        clock: Clock = time.monotonic,
        sleep: Sleeper = asyncio.sleep,
    ) -> None:
        self.settings = settings
        self.limiter = limiter
        self._clock = clock
        self._sleep = sleep
        self._semaphore = asyncio.Semaphore(settings.max_concurrent)
        self._pace_lock = asyncio.Lock()
        self._last_dispatch = float("-inf")
        self._cooldown_until = float("-inf")
        self._in_flight = 0
        self._dispatched = 0
        self._deferred = 0

    # -- introspection ------------------------------------------------------ #

    @property
    def cooldown_remaining(self) -> float:
        return max(0.0, self._cooldown_until - self._clock())

    def stats(self) -> SchedulerStats:
        return SchedulerStats(
            in_flight=self._in_flight,
            dispatched=self._dispatched,
            deferred=self._deferred,
            cooldown_remaining_seconds=round(self.cooldown_remaining, 2),
            tokens_available=self.limiter.snapshot(),
        )

    def note_flood_wait(self, seconds: float) -> None:
        """Hold every operation back for ``seconds``, not just the one that hit it."""
        until = self._clock() + max(0.0, seconds)
        self._cooldown_until = max(self._cooldown_until, until)

    # -- the slot ----------------------------------------------------------- #

    @asynccontextmanager
    async def slot(
        self, operation_class: str, *, tool: str, cost: float = 1.0
    ) -> AsyncGenerator[None]:
        """Acquire the right to make one Telegram request.

        ``cost`` is how many tokens the operation is worth: a call that will
        paginate is charged for the requests it is about to make, not for the
        one tool call it arrives as.
        """
        if not self.settings.enabled:
            self._dispatched += 1
            yield
            return

        acquired = False
        try:
            try:
                await asyncio.wait_for(
                    self._semaphore.acquire(),
                    timeout=self.settings.queue_timeout_seconds,
                )
            except asyncio.TimeoutError:
                self._deferred += 1
                raise RateLimitedError(
                    retry_after_seconds=self.settings.queue_timeout_seconds,
                    reason=(
                        f"waited longer than queue_timeout_seconds for a request "
                        f"slot while {self._in_flight} operations were in flight"
                    ),
                    scope="scheduler",
                ) from None
            acquired = True

            await self._await_cooldown()
            await self.limiter.acquire(operation_class, cost)
            await self._pace()

            # A flood wait can land between the cooldown check and here.
            if self.cooldown_remaining > 0:
                await self._await_cooldown()

            self._in_flight += 1
            self._dispatched += 1
            try:
                yield
            finally:
                self._in_flight -= 1
        finally:
            if acquired:
                self._semaphore.release()

    async def _await_cooldown(self) -> None:
        """Wait out the current cooldown, re-checking after every sleep.

        Another in-flight request can hit a longer flood wait while this one is
        sleeping. Waking at the deadline captured on entry would dispatch into a
        cooldown that is still running, so the remaining time is recomputed each
        time round.
        """
        while True:
            remaining = self.cooldown_remaining
            if remaining <= 0:
                return
            if remaining > self.settings.max_flood_wait_seconds:
                self._deferred += 1
                raise RateLimitedError(
                    retry_after_seconds=remaining,
                    reason=(
                        "Telegram asked this account to wait longer than "
                        "max_flood_wait_seconds "
                        f"({self.settings.max_flood_wait_seconds}s)"
                    ),
                    scope="telegram",
                )
            logger.info("Holding request for %.1fs of Telegram cooldown", remaining)
            await self._sleep(remaining)

    async def _pace(self) -> None:
        interval = self.settings.minimum_interval_ms / 1000.0
        if interval <= 0:
            return
        async with self._pace_lock:
            wait = self._last_dispatch + interval - self._clock()
            if wait > 0:
                await self._sleep(wait)
            self._last_dispatch = self._clock()
