"""The shared request scheduler.

Added by Telegram MCP Enhanced.

Every Telegram operation started through MCP acquires a slot here, so no
individual tool — and no number of concurrent MCP requests — can outrun the
configured limits. The scheduler combines four things:

* a concurrency guard, so parallel MCP calls cannot bypass the limiter;
* per-class token buckets;
* a configurable minimum interval between dispatches;
* a global cooldown, set when Telegram reports a flood wait, which holds back
  every queued operation instead of letting each one discover the wait itself.
"""

from __future__ import annotations

import asyncio
import logging
import time

from collections.abc import AsyncGenerator, Awaitable, Callable, Iterator
from contextlib import asynccontextmanager, contextmanager
from contextvars import ContextVar

from mcp_telegram.config import RateLimitSettings, state_dir
from mcp_telegram.errors import RateLimitedError
from mcp_telegram.reliability.rate_limiter import MultiClassRateLimiter
from mcp_telegram.reliability.state import (
    ReliabilityState,
    STATE_FILE,
    load_state,
    save_state,
)
from mcp_telegram.types import SchedulerStats

__all__ = ["RequestScheduler", "unmetered"]

logger = logging.getLogger(__name__)

Clock = Callable[[], float]
Sleeper = Callable[[float], Awaitable[None]]

RPC_CLASS: ContextVar[str] = ContextVar("rpc_class", default="read")

RPC_EXEMPT: ContextVar[bool] = ContextVar("rpc_exempt", default=False)
"""Set while establishing the connection or logging in.

The cooldown exists to stop the *agent* generating traffic during a flood wait,
not to stop the operator from starting the server. Metering connection and
sign-in requests conflates the two: a flood wait longer than
`max_flood_wait_seconds` survives a restart by design, and would then refuse the
`connect()` inside the lifespan, so the server could not start at all — an
opaque crash in place of the clear, per-tool refusal the operator should see.
Telegram remains the authority either way and re-issues the flood error if it
still wants the account to wait.
"""


@contextmanager
def unmetered() -> Iterator[None]:
    """Run connection or login requests outside the agent's traffic budget."""
    token = RPC_EXEMPT.set(True)
    try:
        yield
    finally:
        RPC_EXEMPT.reset(token)


class RequestScheduler:
    """Serialises and paces Telegram traffic generated by MCP clients."""

    def __init__(
        self,
        settings: RateLimitSettings,
        limiter: MultiClassRateLimiter,
        *,
        clock: Clock = time.monotonic,
        sleep: Sleeper = asyncio.sleep,
        wall_clock: Clock = time.time,
    ) -> None:
        self.settings = settings
        self.limiter = limiter
        self._clock = clock
        self._sleep = sleep
        self._semaphore = asyncio.Semaphore(settings.max_concurrent)
        self._pace_lock = asyncio.Lock()
        self._last_dispatch = float("-inf")
        self._cooldown_until = float("-inf")
        self._in_flight = 0
        self._dispatched = 0
        self._deferred = 0
        self._wall_clock = wall_clock
        self._state_path = state_dir() / STATE_FILE
        if settings.persist_state:
            state = load_state(self._state_path)
            if state is not None:
                now = wall_clock()
                limiter.restore(state.buckets, max(0.0, now - state.saved_at))
                if state.cooldown_until is not None and state.cooldown_until > now:
                    self._cooldown_until = clock() + state.cooldown_until - now

    def _persist(self) -> None:
        """Save before dispatch or returning a flood error, without needing shutdown."""
        if not self.settings.persist_state:
            return
        now = self._wall_clock()
        remaining = self.cooldown_remaining
        state = ReliabilityState.model_validate(
            {
                "version": 1,
                "saved_at": now,
                "buckets": self.limiter.persistent_snapshot(),
                "cooldown_until": now + remaining if remaining > 0 else None,
            }
        )
        save_state(self._state_path, state)

    # -- introspection ------------------------------------------------------ #

    @property
    def cooldown_remaining(self) -> float:
        return max(0.0, self._cooldown_until - self._clock())

    def stats(self) -> SchedulerStats:
        return SchedulerStats(
            in_flight=self._in_flight,
            dispatched=self._dispatched,
            deferred=self._deferred,
            cooldown_remaining_seconds=round(self.cooldown_remaining, 2),
            tokens_available=self.limiter.snapshot(),
        )

    def note_flood_wait(self, seconds: float) -> None:
        """Hold every operation back for ``seconds``, not just the one that hit it."""
        until = self._clock() + max(0.0, seconds)
        self._cooldown_until = max(self._cooldown_until, until)
        self._persist()

    # -- the slot ----------------------------------------------------------- #

    @asynccontextmanager
    async def slot(self, operation_class: str, *, tool: str) -> AsyncGenerator[None]:
        """Bound tool concurrency without charging speculative Telegram traffic.

        The RPC boundary inherits the class through task-local context. It must
        never acquire this semaphore: the tool already holds it while paging.
        """
        token = RPC_CLASS.set(operation_class)
        acquired = False
        try:
            if self.settings.enabled:
                self._refuse_if_cooldown_exceeds_limit()
                try:
                    await asyncio.wait_for(
                        self._semaphore.acquire(),
                        timeout=self.settings.queue_timeout_seconds,
                    )
                except asyncio.TimeoutError:
                    self._deferred += 1
                    raise RateLimitedError(
                        retry_after_seconds=self.settings.queue_timeout_seconds,
                        reason=(
                            "waited longer than queue_timeout_seconds for a request "
                            f"slot while {self._in_flight} operations were in flight"
                        ),
                        scope="scheduler",
                    ) from None
                acquired = True
                self._refuse_if_cooldown_exceeds_limit()
            self._in_flight += 1
            try:
                yield
            finally:
                self._in_flight -= 1
        finally:
            if acquired:
                self._semaphore.release()
            RPC_CLASS.reset(token)

    async def meter_rpc(self) -> None:
        """Charge actual RPC admissions without re-entering the tool semaphore."""
        if RPC_EXEMPT.get():
            return
        if self.settings.enabled:
            self._refuse_if_cooldown_exceeds_limit()
            await self.limiter.acquire(RPC_CLASS.get())
            self._persist()
            await self._dispatch_gate()
        self._dispatched += 1

    def _refuse_if_cooldown_exceeds_limit(self) -> None:
        """Report rather than block when Telegram's wait is longer than allowed."""
        remaining = self.cooldown_remaining
        if remaining > self.settings.max_flood_wait_seconds:
            self._deferred += 1
            raise RateLimitedError(
                retry_after_seconds=remaining,
                reason=(
                    "Telegram asked this account to wait longer than "
                    f"max_flood_wait_seconds ({self.settings.max_flood_wait_seconds}s)"
                ),
                scope="telegram",
            )

    async def _dispatch_gate(self) -> None:
        """The single gate every request passes through immediately before dispatch.

        Cooldown and pacing are enforced together, under one lock, re-checking
        both after every sleep. Keeping them separate allowed two failures: a
        waiter could wake at a cooldown deadline another request had already
        extended, and requests released by a cooldown could dispatch as a burst
        because they had each satisfied the pacing interval before waiting.
        """
        interval = self.settings.minimum_interval_ms / 1000.0
        async with self._pace_lock:
            while True:
                remaining = self.cooldown_remaining
                if remaining > 0:
                    self._refuse_if_cooldown_exceeds_limit()
                    logger.info(
                        "Holding request for %.1fs of Telegram cooldown", remaining
                    )
                    await self._sleep(remaining)
                    continue

                wait = self._last_dispatch + interval - self._clock()
                if wait > 0:
                    await self._sleep(wait)
                    continue

                self._last_dispatch = self._clock()
                return
